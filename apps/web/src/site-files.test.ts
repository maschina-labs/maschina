import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { CONTENT_PATHS } from "./app.tsx";
import { FILES, ROUTES } from "./routes.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (file: string) => readFileSync(resolve(root, "public", file), "utf8");
const ORIGIN = "https://maschina.dev";
const NO_LONG_DASH = new RegExp(`[${String.fromCharCode(0x2013)}${String.fromCharCode(0x2014)}]`);

/** The addresses on this site that a text file links to, each written out in full. */
const own = (text: string) =>
	[...text.matchAll(/https:\/\/maschina\.dev(\/[^\s)>"']*)?/g)].map((match) => match[1] ?? "/");

describe("every file here is real and is the one it is called", () => {
	it("has each of the plain files the site names, and no file that is not named", () => {
		for (const href of Object.keys(FILES))
			expect(existsSync(resolve(root, "public", `.${href}`)), href).toBe(true);
	});

	it.each([
		"robots.txt",
		"sitemap.xml",
		"llms.txt",
		"llms-full.txt",
		"SKILL.md",
		"humans.txt",
		".well-known/security.txt",
	])(
		"%s is written the way the site is: no long dashes, no placeholders, no AI vendor wording, no shouting",
		(file) => {
			const text = read(file);
			expect(text).not.toMatch(NO_LONG_DASH);
			expect(text).not.toMatch(/lorem|\btodo\b|\btbd\b|\bxxx\b/i);
			expect(text).not.toMatch(/\b(chatgpt|copilot|generated by)\b/i);
			expect(text).not.toMatch(/!/);
		},
	);
});

describe("robots.txt", () => {
	const text = read("robots.txt");

	it("lets everything be read, hides nothing, and says where the sitemap is", () => {
		expect(text).toMatch(/^User-agent: \*$/m);
		expect(text).toMatch(/^Allow: \/$/m);
		expect(text).not.toMatch(/^Disallow: \/\s*$/m);
		expect(text).toContain(`Sitemap: ${ORIGIN}/sitemap.xml`);
	});
});

describe("sitemap.xml", () => {
	const text = read("sitemap.xml");
	const urls = [...text.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1] ?? "");

	it("lists the pages that have something on them, each once, and not the blank ones", () => {
		const expected = CONTENT_PATHS.map((path) =>
			path === "/" ? `${ORIGIN}/` : `${ORIGIN}${path}`,
		).sort();
		expect([...urls].sort()).toEqual(expected);
		expect(new Set(urls).size).toBe(urls.length);
		for (const path of Object.keys(ROUTES).filter((route) => !CONTENT_PATHS.includes(route)))
			expect(urls, path).not.toContain(`${ORIGIN}${path}`);
	});

	it("is a sitemap, and promises no date it does not know", () => {
		expect(text).toContain('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">');
		expect(text).not.toMatch(/<lastmod>|<changefreq>|<priority>/);
	});
});

describe("security.txt", () => {
	const text = read(".well-known/security.txt");

	it("has what the standard asks for: a contact, an expiry under a year away, a policy, and where it lives", () => {
		expect(text).toMatch(/^Contact: mailto:security@maschina\.dev$/m);
		expect(text).toMatch(
			/^Contact: https:\/\/github\.com\/maschina-labs\/maschina\/security\/advisories\/new$/m,
		);
		expect(text).toContain(`Policy: ${ORIGIN}/disclosure`);
		expect(text).toContain(`Canonical: ${ORIGIN}/.well-known/security.txt`);
		expect(text).toMatch(/^Preferred-Languages: en$/m);
		const expires = /^Expires: (.+)$/m.exec(text)?.[1] ?? "";
		const days = (Date.parse(expires) - Date.now()) / 86_400_000;
		expect(days, "must not have expired").toBeGreaterThan(0);
		expect(days, "the standard allows less than a year").toBeLessThan(366);
	});
});

describe("llms.txt, llms-full.txt and SKILL.md", () => {
	it("llms.txt follows the format: a name, a one line summary, then sections of links with a line each", () => {
		const text = read("llms.txt");
		expect(text).toMatch(/^# Maschina\n/);
		expect(text).toMatch(/^> .+/m);
		expect(text).toMatch(/^## .+/m);
		expect(text).toMatch(/^- \[[^\]]+\]\(https:\/\/[^)]+\): .+/m);
	});

	it.each(["llms.txt", "llms-full.txt", "SKILL.md"])(
		"%s links only to pages and files this site really has",
		(file) => {
			for (const path of own(read(file))) {
				const clean = path.replace(/[.,;]+$/, "");
				expect(clean === "/" || clean in ROUTES || clean in FILES, `${file}: ${clean}`).toBe(true);
			}
		},
	);

	it("SKILL.md opens with the front matter a skill needs, a name and a description", () => {
		const text = read("SKILL.md");
		expect(text).toMatch(/^---\nname: maschina\ndescription: .{40,}\n---\n/);
	});

	it.each(["llms.txt", "llms-full.txt", "SKILL.md"])(
		"%s claims nothing that is not true: no audit, no users, no returns, no live API it does not have",
		(file) => {
			const text = read(file);
			expect(text).toMatch(/not (been )?independently audited|has not been audited/i);
			expect(text).not.toMatch(/\d+%|\$\d|\busers\b|customers|profit|guarantee/i);
			expect(text).not.toMatch(/\b(MCP server is|install the mcp|npm install|pip install)\b/i);
		},
	);

	it("llms-full.txt says what the pages on this site say, in one place, including the risks", () => {
		const text = read("llms-full.txt");
		expect(text).toMatch(/lose (some or )?all of the money/i);
		expect(text).toMatch(/source-available, not open source/i);
		for (const heading of ["About", "Roadmap", "Risk", "Terms"])
			expect(text, heading).toContain(heading);
	});
});

describe("humans.txt", () => {
	it("names the company and the site, not a person's private details", () => {
		const text = read("humans.txt");
		expect(text).toMatch(/Maschina Labs/);
		expect(text).toMatch(/Alberta, Canada/);
		expect(text).not.toMatch(/@(gmail|icloud|outlook|hotmail)\./i);
		expect(text).not.toMatch(/asher@|info@/i);
	});
});
